const uiLanguage = localStorage.getItem("workflow-language") === "tr" ? "tr" : "en";
const uiLocale = uiLanguage === "en" ? "en-US" : "tr-TR";

function tr(source, values) {
  const message = uiLanguage === "en" && Object.hasOwn(english, source)
    ? english[source]
    : source;
  if (!values) return message;
  return message.replace(/\{([a-z][a-z0-9]*)\}/gi, (token, key) =>
    Object.hasOwn(values, key) ? String(values[key]) : token,
  );
}

const messagePatterns = uiLanguage === "en"
  ? Object.entries(english)
      .filter(([source]) => source.includes("{0}"))
      .map(([source, translated]) => [
        new RegExp("^" + source.split(/\{\d+\}/)
          .map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))
          .join("([\\s\\S]+?)") + "$"),
        translated,
      ])
  : [];

function tMessage(source) {
  if (uiLanguage !== "en" || typeof source !== "string") return source;
  if (Object.hasOwn(english, source)) return english[source];
  for (const [pattern, translated] of messagePatterns) {
    const match = pattern.exec(source);
    if (match) return translated.replace(/\{(\d+)\}/g, (_, index) => match[Number(index) + 1]);
  }
  return source;
}

function uiError(error) {
  if (uiLanguage === "tr") return String(error);
  return tMessage(error?.message || String(error));
}

function usageLabel(source) {
  if (uiLanguage !== "en") return source;
  return source.split(" · ").map((part) => {
    const match = /^(\d+) (saatlik|günlük|dakikalık)$/.exec(part);
    if (!match) return tMessage(part);
    const unit = { saatlik: "hour", günlük: "day", dakikalık: "minute" }[match[2]];
    return match[1] + "-" + unit;
  }).join(" · ");
}

function countLabel(count, source) {
  const singular = source + " (tekil)";
  return tr(uiLanguage === "en" && count === 1 && Object.hasOwn(english, singular) ? singular : source, { count });
}

function translateMarkup() {
  document.documentElement.lang = uiLanguage;
  if (uiLanguage !== "en") return;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement.closest("script, style")) continue;
    const content = node.nodeValue.trim();
    if (content)
      node.nodeValue = node.nodeValue.replace(content, tr(content.replace(/\s+/g, " ")));
  }
  for (const element of document.querySelectorAll("[title], [aria-label], [placeholder], [alt]")) {
    for (const attribute of ["title", "aria-label", "placeholder", "alt"]) {
      if (element.hasAttribute(attribute))
        element.setAttribute(attribute, tr(element.getAttribute(attribute)));
    }
  }
}

